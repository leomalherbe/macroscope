/* Compiles the French text of a page (dev/i18n/<page>.fr.txt) into i18n/fr-<page>.js,
   the dictionary that i18n.js applies. Usage: node dev/i18n-build.js desk
   Format of the source: see the head of dev/i18n/desk.fr.txt. An English line starting with « | » is
   literal (for HTML with # in links or & in entities: the model page); one starting with « ~ » is a raw
   regular expression, the French then uses $1 (as is) and %1 (translated). */
const fs = require('fs'), path = require('path');
const page = process.argv[2] || 'desk';
const root = path.join(__dirname, '..');
const lines = fs.readFileSync(path.join(__dirname, 'i18n', page + '.fr.txt'), 'utf8').split('\n');
const NUM = '([+−±-]?\\d+(?:[.,]\\d+)?)', ANY = '(.+?)';
function typo(s) { return s.replace(/ ([:;?!])/g, ' $1').replace(/(\d|\$\d|#|\}) %/g, '$1 %').replace(/« /g, '« ').replace(/ »/g, ' »'); }
function esc(s) { return s.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&'); }
const str = {}, re = [], seen = new Set();
let title = null;
for (let i = 0; i < lines.length; i++) {
  const en = lines[i];
  if (!en.trim() || en.startsWith('//')) continue;
  const fl = lines[i + 1] || '';
  if (!fl.startsWith('=> ')) throw new Error('line ' + (i + 2) + ': expected « => » after « ' + en + ' »');
  i++;
  let fr = fl.slice(3);
  if (seen.has(en)) throw new Error('duplicate: ' + en); seen.add(en);
  if (en === '@title') { title = fr; continue; }
  if (en.startsWith('~ ')) { re.push([en.slice(2), typo(fr)]); continue; }   /* raw regular expression; $1 / %1 in the French */
  if (en.startsWith('| ')) { str[en.slice(2)] = typo(fr); continue; }   /* literal: # @ & are plain characters */
  const kinds = []; let rx = '';
  for (const ch of en) {
    if (ch === '#') { kinds.push('$'); rx += NUM; }
    else if (ch === '@') { kinds.push('%'); rx += ANY; }
    else if (ch === '&') { kinds.push('$'); rx += ANY; }
    else rx += esc(ch);
  }
  if (!kinds.length) { str[en] = typo(fr); continue; }
  let n = 0, out = '';
  for (let j = 0; j < fr.length; j++) {
    const ch = fr[j], m = /^\{(\d)\}/.exec(fr.slice(j));
    if (m) { const k = +m[1]; out += kinds[k - 1] + k; j += 2; continue; }
    if (ch === '#' || ch === '@' || ch === '&') { n++; if (n > kinds.length) throw new Error('too many placeholders: ' + fr); out += kinds[n - 1] + n; }
    else out += ch;
  }
  re.push([rx, typo(out)]);
}
const d = { str: str, re: re }; if (title) d.title = title;
const out = '/* Macroscope — French text of ' + page + '.html. GENERATED by dev/i18n-build.js from dev/i18n/' + page + '.fr.txt: edit that file, not this one. */\nMXL.add(\'fr\', ' + JSON.stringify(d, null, 0).replace(/\],\[/g, '],\n[').replace(/","/g, '",\n"') + ');\n';
fs.writeFileSync(path.join(root, 'i18n', 'fr-' + page + '.js'), out);
console.log('i18n/fr-' + page + '.js:', Object.keys(str).length, 'strings,', re.length, 'patterns');
